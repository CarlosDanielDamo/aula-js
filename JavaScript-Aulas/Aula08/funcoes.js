function calcularMedia(nota1, nota2) {
    let media = (nota1 + nota2) / 2
    return media
}

console.log(`A média do aluno é ${calcularMedia(10, 7)}`);

const nomeFuncao = (no1, no2) => {
    let media = (no1 + no2) / 2
    return media;
}

console.log(`A média do aluno é ${nomeFuncao(4, 8)}`);